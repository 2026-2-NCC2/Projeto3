    updated_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_proposta_item_fornecedor UNIQUE (item_custo_id, fornecedor_id),
    CONSTRAINT uq_proposta_selecionada UNIQUE (selecao_chave),
    CONSTRAINT fk_propostas_item FOREIGN KEY (item_custo_id)
