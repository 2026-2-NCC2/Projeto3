-- ---------------------------------------------------------------------------
-- TRIGGER PARA SUBSTITUIR ON UPDATE CURRENT_TIMESTAMP DO MYSQL
-- Aplicado as tabelas que tinham updated_at/atualizado_em automaticos.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION atualizar_timestamp_modificacao()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION atualizar_timestamp_atualizado_em()
RETURNS TRIGGER AS $$
BEGIN
    NEW.atualizado_em = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION atualizar_timestamp_atualizado_ms()
RETURNS TRIGGER AS $$
BEGIN
    NEW.atualizado_ms = (EXTRACT(EPOCH FROM clock_timestamp()) * 1000)::BIGINT;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_usuarios_updated_at ON usuarios;
CREATE TRIGGER trg_usuarios_updated_at BEFORE UPDATE ON usuarios
FOR EACH ROW EXECUTE FUNCTION atualizar_timestamp_modificacao();
DROP TRIGGER IF EXISTS trg_eventos_updated_at ON eventos;
CREATE TRIGGER trg_eventos_updated_at BEFORE UPDATE ON eventos
FOR EACH ROW EXECUTE FUNCTION atualizar_timestamp_modificacao();
DROP TRIGGER IF EXISTS trg_itens_custo_updated_at ON itens_custo;
CREATE TRIGGER trg_itens_custo_updated_at BEFORE UPDATE ON itens_custo
FOR EACH ROW EXECUTE FUNCTION atualizar_timestamp_modificacao();
DROP TRIGGER IF EXISTS trg_custos_evento_updated_at ON custos_evento;
CREATE TRIGGER trg_custos_evento_updated_at BEFORE UPDATE ON custos_evento
