DROP TRIGGER IF EXISTS trg_revendas_atualizado_em ON revendas;
CREATE TRIGGER trg_revendas_atualizado_em BEFORE UPDATE ON revendas
FOR EACH ROW EXECUTE FUNCTION atualizar_timestamp_atualizado_em();

