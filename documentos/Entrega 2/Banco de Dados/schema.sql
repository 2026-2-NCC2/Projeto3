-- OBSERVACOES IMPORTANTES:
-- 1. As colunas *_ms continuam sendo BIGINT em milissegundos Unix.
-- 2. O campo reservas.anuncio_id nao recebeu FK porque o schema original nao
--    declarava essa constraint e a relacao pode depender da ordem do fluxo.
-- 3. original_pedido_id em ingressos tambem foi mantido sem FK, como no original.
-- 4. O schema original nao define FK em auditoria.usuario_id nem recuperacoes.usuario_id.
-- 5. O campo anuncios.chave_ativa e uma coluna gerada STORED no PostgreSQL.
-- 6. Se a aplicacao enviar updated_at/atualizado_em manualmente, o trigger
--    sobrescrevera esses valores com o horario atual.
