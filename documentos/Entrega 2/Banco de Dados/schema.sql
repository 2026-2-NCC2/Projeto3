-- ---------------------------------------------------------------------------
-- USUARIOS
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS usuarios (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome         VARCHAR(120) NOT NULL,
    email        VARCHAR(160) NOT NULL,
    senha_hash   VARCHAR(255) NOT NULL,
    perfil       perfil_usuario NOT NULL,
    status       status_usuario NOT NULL DEFAULT 'pendente',
    telefone     VARCHAR(20),
    razao_social VARCHAR(160),
    documento    CHAR(14),
    area_atuacao VARCHAR(120),
    aprovado_por INTEGER,
    aprovado_em  TIMESTAMP,
    created_at   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_usuarios_email UNIQUE (email),
    CONSTRAINT uq_usuarios_documento UNIQUE (documento),
    CONSTRAINT fk_usuarios_aprovador FOREIGN KEY (aprovado_por)
        REFERENCES usuarios(id) ON DELETE SET NULL,
    CONSTRAINT chk_usuarios_fornecedor
        CHECK (perfil <> 'fornecedor' OR documento IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS idx_usuarios_perfil_status
    ON usuarios(perfil, status);

-- ---------------------------------------------------------------------------
-- EVENTOS
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS eventos (
    id                       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizador_id           INTEGER NOT NULL,
    nome                     VARCHAR(120) NOT NULL,
    descricao                TEXT,
    local_evento             VARCHAR(200) NOT NULL,
    data_inicio              TIMESTAMP NOT NULL,
    data_fim                 TIMESTAMP NOT NULL,
    publico_minimo           INTEGER NOT NULL DEFAULT 0 CHECK (publico_minimo >= 0),
    publico_maximo           INTEGER NOT NULL,
    publico_esperado         INTEGER,
    margem_lucro_percentual  NUMERIC(5,2) NOT NULL DEFAULT 0.00,
    status                   status_evento NOT NULL DEFAULT 'rascunho',
    created_at               TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at               TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_eventos_organizador FOREIGN KEY (organizador_id)
        REFERENCES usuarios(id) ON DELETE RESTRICT,
    CONSTRAINT chk_eventos_datas CHECK (data_fim >= data_inicio),
    CONSTRAINT chk_eventos_publico
        CHECK (publico_maximo > 0 AND publico_maximo >= publico_minimo),
    CONSTRAINT chk_eventos_esperado
        CHECK (publico_esperado IS NULL OR
              (publico_esperado >= publico_minimo AND publico_esperado <= publico_maximo)),
    CONSTRAINT chk_eventos_margem
        CHECK (margem_lucro_percentual >= 0 AND margem_lucro_percentual < 100)
);

CREATE INDEX IF NOT EXISTS idx_eventos_organizador ON eventos(organizador_id);
CREATE INDEX IF NOT EXISTS idx_eventos_status ON eventos(status);
CREATE INDEX IF NOT EXISTS idx_eventos_data_inicio ON eventos(data_inicio);

